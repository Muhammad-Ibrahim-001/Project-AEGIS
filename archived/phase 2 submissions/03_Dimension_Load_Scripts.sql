-- ==============================================================================
-- 1. DIM_DATE POPULATION (Universal Calendar: 2021-01-01 to 2024-12-31, 1,461 Days)
-- ==============================================================================

-- Databricks Spark SQL Sequence Generation
INSERT OVERWRITE gold_warehouse.dim_date
SELECT 
    CAST(DATE_FORMAT(calendar_date, 'yyyyMMdd') AS INT) AS date_key,
    calendar_date,
    YEAR(calendar_date) AS calendar_year,
    QUARTER(calendar_date) AS calendar_quarter,
    MONTH(calendar_date) AS calendar_month,
    DATE_FORMAT(calendar_date, 'MMMM') AS month_name,
    DAY(calendar_date) AS day_of_month,
    DAYOFWEEK(calendar_date) AS day_of_week,
    DATE_FORMAT(calendar_date, 'EEEE') AS day_name,
    CASE WHEN DAYOFWEEK(calendar_date) IN (1, 7) THEN TRUE ELSE FALSE END AS is_weekend,
    CASE 
        WHEN MONTH(calendar_date) IN (12, 1, 2) THEN 'Winter'
        WHEN MONTH(calendar_date) IN (3, 4, 5) THEN 'Spring'
        WHEN MONTH(calendar_date) IN (6, 7, 8) THEN 'Summer'
        ELSE 'Fall'
    END AS season_name,
    CASE 
        WHEN MONTH(calendar_date) IN (7, 8) THEN TRUE 
        ELSE FALSE 
    END AS is_summer_peak,
    CASE 
        WHEN MONTH(calendar_date) IN (1, 2) THEN TRUE 
        ELSE FALSE 
    END AS is_winter_freeze
FROM (
    SELECT EXPLODE(SEQUENCE(DATE '2021-01-01', DATE '2024-12-31', INTERVAL 1 DAY)) AS calendar_date
);

-- ==============================================================================
-- 2. DIM_PLANT POPULATION (Surrogate Key Generation + Default Row)
-- ==============================================================================

-- Step 2A: Seed default unknown member (-1) if not present
-- Note: Uses GENERATED BY DEFAULT AS IDENTITY or explicit key insertion
INSERT INTO gold_warehouse.dim_plant (
    orispl_code, plant_name, utility_id, utility_name, 
    latitude, longitude, state_code, county_name, ba_code, epa_region
)
SELECT 
    -1 AS orispl_code, 
    'Unknown Power Plant' AS plant_name, 
    -1 AS utility_id, 
    'Unknown Utility' AS utility_name,
    0.0 AS latitude, 
    0.0 AS longitude, 
    'XX' AS state_code, 
    'Unknown County' AS county_name, 
    'UNKN' AS ba_code, 
    -1 AS epa_region
WHERE NOT EXISTS (
    SELECT 1 FROM gold_warehouse.dim_plant WHERE orispl_code = -1
);

-- Step 2B: Clean, deduplicate and populate plants from Silver Conformed
MERGE INTO gold_warehouse.dim_plant AS target
USING (
    SELECT 
        CAST(orispl_code AS INT) AS orispl_code,
        TRIM(plant_name) AS plant_name,
        TRY_CAST(utility_id AS INT) AS utility_id,
        TRIM(utility_name) AS utility_name,
        TRY_CAST(latitude AS DECIMAL(9,6)) AS latitude,
        TRY_CAST(longitude AS DECIMAL(9,6)) AS longitude,
        UPPER(TRIM(state_code)) AS state_code,
        TRIM(county_name) AS county_name,
        UPPER(TRIM(ba_code)) AS ba_code,
        TRY_CAST(epa_region AS INT) AS epa_region,
        COALESCE(TRY_CAST(is_chp AS BOOLEAN), FALSE) AS is_combined_heat_power
    FROM (
        SELECT *, 
               ROW_NUMBER() OVER (PARTITION BY orispl_code ORDER BY batch_id DESC) AS rn
        FROM silver_conformed.silver_plants_master
        WHERE orispl_code IS NOT NULL AND orispl_code != '' AND orispl_code != '-9999'
    )
    WHERE rn = 1
) AS source
ON target.orispl_code = source.orispl_code
WHEN MATCHED THEN UPDATE SET 
    target.plant_name = source.plant_name,
    target.utility_id = source.utility_id,
    target.utility_name = source.utility_name,
    target.latitude = source.latitude,
    target.longitude = source.longitude,
    target.state_code = source.state_code,
    target.county_name = source.county_name,
    target.ba_code = source.ba_code,
    target.epa_region = source.epa_region,
    target.is_combined_heat_power = source.is_combined_heat_power
WHEN NOT MATCHED THEN INSERT (
    orispl_code, plant_name, utility_id, utility_name, 
    latitude, longitude, state_code, county_name, ba_code, epa_region, is_combined_heat_power
) VALUES (
    source.orispl_code, source.plant_name, source.utility_id, source.utility_name,
    source.latitude, source.longitude, source.state_code, source.county_name, 
    source.ba_code, source.epa_region, source.is_combined_heat_power
);

-- ==============================================================================
-- 3. DIM_GENERATOR POPULATION (SCD TYPE 2 LIFECYCLE TRACKING)
-- ==============================================================================

-- Step 3A: Seed default unknown member (-1)
INSERT INTO gold_warehouse.dim_generator (
    orispl_code, generator_id, prime_mover_code, primary_energy_source,
    nameplate_capacity_mw, operating_status, valid_from, valid_to, is_current
)
SELECT 
    -1 AS orispl_code, 
    '-1' AS generator_id, 
    'UN' AS prime_mover_code, 
    'UN' AS primary_energy_source,
    0.0 AS nameplate_capacity_mw, 
    'UN' AS operating_status,
    TIMESTAMP '1900-01-01 00:00:00' AS valid_from,
    TIMESTAMP '9999-12-31 23:59:59' AS valid_to,
    TRUE AS is_current
WHERE NOT EXISTS (
    SELECT 1 FROM gold_warehouse.dim_generator WHERE orispl_code = -1 AND generator_id = '-1'
);

-- Step 3B: Expire obsolete versions where operating status or capacity changed
MERGE INTO gold_warehouse.dim_generator AS target
USING (
    SELECT 
        CAST(s.orispl_code AS INT) AS orispl_code,
        TRIM(s.generator_id) AS generator_id,
        UPPER(TRIM(s.operating_status)) AS new_status,
        TRY_CAST(s.nameplate_capacity_mw AS DECIMAL(10,2)) AS new_capacity,
        CURRENT_TIMESTAMP() AS effective_timestamp
    FROM silver_conformed.silver_generators_conformed s
) AS source
ON target.orispl_code = source.orispl_code
   AND target.generator_id = source.generator_id
   AND target.is_current = TRUE
   AND (target.operating_status != source.new_status 
        OR target.nameplate_capacity_mw != source.new_capacity)
WHEN MATCHED THEN UPDATE SET
    target.valid_to = source.effective_timestamp,
    target.is_current = FALSE;

-- Step 3C: Insert new active SCD Type 2 record for new or changed units
INSERT INTO gold_warehouse.dim_generator (
    orispl_code, generator_id, prime_mover_code, primary_energy_source,
    nameplate_capacity_mw, operating_status, valid_from, valid_to, is_current
)
SELECT 
    CAST(s.orispl_code AS INT),
    TRIM(s.generator_id),
    UPPER(TRIM(s.prime_mover)),
    UPPER(TRIM(s.energy_source_1)),
    TRY_CAST(s.nameplate_capacity_mw AS DECIMAL(10,2)),
    UPPER(TRIM(s.operating_status)),
    CURRENT_TIMESTAMP() AS valid_from,
    TIMESTAMP '9999-12-31 23:59:59' AS valid_to,
    TRUE AS is_current
FROM silver_conformed.silver_generators_conformed s
WHERE NOT EXISTS (
    SELECT 1 
    FROM gold_warehouse.dim_generator d
    WHERE d.orispl_code = CAST(s.orispl_code AS INT)
      AND d.generator_id = TRIM(s.generator_id)
      AND d.is_current = TRUE
);

-- ==============================================================================
-- 4. DIM_BALANCING_AUTHORITY POPULATION (Grid Operators)
-- ==============================================================================

-- Seed default unknown member (-1)
INSERT INTO gold_warehouse.dim_balancing_authority (ba_code, ba_name, region, is_active)
SELECT 'UNKN', 'Unknown Balancing Authority', 'UNKNOWN', TRUE
WHERE NOT EXISTS (
    SELECT 1 FROM gold_warehouse.dim_balancing_authority WHERE ba_code = 'UNKN'
);

-- Upsert distinct balancing authorities
MERGE INTO gold_warehouse.dim_balancing_authority AS target
USING (
    SELECT DISTINCT 
        UPPER(TRIM(ba_code)) AS ba_code,
        COALESCE(TRIM(ba_name), UPPER(TRIM(ba_code))) AS ba_name,
        COALESCE(TRIM(region), 'UNKNOWN') AS region
    FROM silver_conformed.silver_grid_hourly
    WHERE ba_code IS NOT NULL AND TRIM(ba_code) != ''
) AS source
ON target.ba_code = source.ba_code
WHEN MATCHED THEN UPDATE SET 
    target.ba_name = source.ba_name,
    target.region = source.region
WHEN NOT MATCHED THEN INSERT (ba_code, ba_name, region, is_active)
VALUES (source.ba_code, source.ba_name, source.region, TRUE);

-- ==============================================================================
-- 5. DIM_WEATHER_STATION POPULATION (NOAA Surface Weather)
-- ==============================================================================

-- Seed default unknown member (-1)
INSERT INTO gold_warehouse.dim_weather_station (
    station_id, station_name, state_code, latitude, longitude, elevation_m
)
SELECT '999999-99999', 'Unknown Weather Station', 'XX', 0.0, 0.0, 0.0
WHERE NOT EXISTS (
    SELECT 1 FROM gold_warehouse.dim_weather_station WHERE station_id = '999999-99999'
);

-- Upsert weather station entities
MERGE INTO gold_warehouse.dim_weather_station AS target
USING (
    SELECT DISTINCT 
        TRIM(station_id) AS station_id,
        TRIM(station_name) AS station_name,
        UPPER(TRIM(state_code)) AS state_code,
        TRY_CAST(latitude AS DECIMAL(9,6)) AS latitude,
        TRY_CAST(longitude AS DECIMAL(9,6)) AS longitude,
        TRY_CAST(elevation_m AS DECIMAL(7,2)) AS elevation_m
    FROM silver_conformed.silver_weather_hourly
    WHERE station_id IS NOT NULL AND TRIM(station_id) != ''
) AS source
ON target.station_id = source.station_id
WHEN MATCHED THEN UPDATE SET
    target.station_name = source.station_name,
    target.state_code = source.state_code,
    target.latitude = source.latitude,
    target.longitude = source.longitude,
    target.elevation_m = source.elevation_m
WHEN NOT MATCHED THEN INSERT (
    station_id, station_name, state_code, latitude, longitude, elevation_m
) VALUES (
    source.station_id, source.station_name, source.state_code, 
    source.latitude, source.longitude, source.elevation_m
);
